#!/usr/bin/env bash
# ===================================================================
#  seed-config.sh - create deploy/linux/demo/config.sh from config.example.sh
#  (carrying over local values from deploy/windows/demo/config.bat if present).
#
#  Usage:
#    ./seed-config.sh            create config.sh if missing
#    ./seed-config.sh --force    regenerate, overwriting config.sh
# ===================================================================
set -euo pipefail

DEPLOY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FORCE=0
for arg in "$@"; do
  case "$arg" in
    -f|--force|-Force) FORCE=1 ;;
    *)
      echo "[seed-demo] Unknown option: $arg (use --force to overwrite)" >&2
      exit 1
      ;;
  esac
done

TEMPLATE="${DEPLOY_DIR}/config.example.sh"
OUT_FILE="${DEPLOY_DIR}/config.sh"
BAT_FILE="${DEPLOY_DIR}/../../windows/demo/config.bat"

if [[ ! -f "$TEMPLATE" ]]; then
  echo "[seed-demo] config.example.sh not found at $TEMPLATE" >&2
  exit 1
fi

if [[ -f "$OUT_FILE" && "$FORCE" -eq 0 ]]; then
  echo "[seed-demo] config.sh already exists - leaving it untouched (use --force to regenerate)."
  exit 0
fi

python3 - "$TEMPLATE" "$OUT_FILE" "$BAT_FILE" <<'PY'
import os
import re
import sys

template_path, out_path, bat_path = sys.argv[1:4]

bat: dict[str, str] = {}
if os.path.isfile(bat_path):
    with open(bat_path, "r", encoding="utf-8", errors="replace") as f:
        for raw in f:
            m = re.match(r'^\s*set\s+"?([A-Za-z_][A-Za-z0-9_]*)=([^"\r\n]*)', raw)
            if m:
                val = m.group(2).strip()
                if val and "%" not in val:
                    bat[m.group(1)] = val

portable_keys = {
    "DROPLET_NAME",
    "SHARED_DROPLET_IP",
    "REGION",
    "SIZE",
    "DEMO_PORT",
    "DEMO_BIND",
    "DEMO_MEM_LIMIT",
    "DEMO_CPU_LIMIT",
    "DEMO_MAX_USERS",
    "DEMO_LAG_WARNING_USERS",
    "DEMO_IDLE_TIMEOUT_SECONDS",
    "DEMO_MAX_CONCURRENT_COMPUTE",
    "DOMAIN",
    "CF_TUNNEL_TOKEN",
}

with open(template_path, "r", encoding="utf-8") as f:
    tpl_lines = [line.rstrip("\r\n") for line in f]

out_lines: list[str] = []
for idx, line in enumerate(tpl_lines):
    if idx == 1:
        out_lines.append("# AUTO-GENERATED by seed-config.sh - regenerate with: ./seed-config.sh --force")
    m = re.match(r'^([A-Za-z_][A-Za-z0-9_]*)=(.*)$', line)
    if m and m.group(1) in portable_keys and m.group(1) in bat:
        key = m.group(1)
        escaped = bat[key].replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`")
        out_lines.append(f'{key}="{escaped}"')
        continue
    out_lines.append(line)

with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out_lines) + "\n")

os.chmod(out_path, 0o600)
print(f"[seed-demo] Wrote {out_path}")
PY
